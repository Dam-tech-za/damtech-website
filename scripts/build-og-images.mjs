#!/usr/bin/env node
/**
 * Builds social-share (Open Graph) copies of the photos used as og:image.
 *
 *   node scripts/build-og-images.mjs
 *
 * Originals in public/images/ are read only and never modified. Each source is
 * resized to 1200×630 (centre crop, the size WhatsApp/Facebook/LinkedIn expect)
 * and saved as a progressive JPEG under 300 KB in public/og/. The list of
 * built files is written to lib/og-images.generated.ts so metadata only points
 * at a derivative that actually exists.
 *
 * Sources = every og:image found by the last live crawl
 * (docs/audit/01-route-inventory.json) plus lib/images.ts DEFAULT_OG_IMAGE.
 * Re-run after adding a page that uses a new og image.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const MAX_BYTES = 300 * 1024;
const OUT_DIR = "public/og";
const inventory = JSON.parse(fs.readFileSync("docs/audit/01-route-inventory.json", "utf8"));

const sources = new Set(["/images/hdpe-dam-lining-field-installation.webp"]);
for (const route of Object.values(inventory.routes)) {
  const image = route.desktop?.og?.image;
  if (image) sources.add(new URL(image).pathname);
}

fs.mkdirSync(OUT_DIR, { recursive: true });
const built = [];
for (const src of [...sources].sort()) {
  const file = path.join("public", src);
  if (!src.startsWith("/images/") || !fs.existsSync(file)) {
    console.warn(`skip ${src} (not a local /images/ file)`);
    continue;
  }
  const name = path.basename(src).replace(/\.[a-z0-9]+$/i, "");
  const out = path.join(OUT_DIR, `${name}.jpg`);
  let quality = 82;
  let buffer;
  do {
    buffer = await sharp(file)
      .rotate()
      .resize(1200, 630, { fit: "cover", position: "centre" })
      .jpeg({ quality, progressive: true, mozjpeg: true })
      .toBuffer();
    quality -= 6;
  } while (buffer.length > MAX_BYTES && quality > 40);
  fs.writeFileSync(out, buffer);
  built.push(src);
  console.log(`${out}  ${(buffer.length / 1024).toFixed(0)} KB  q${quality + 6}`);
}

fs.writeFileSync(
  "lib/og-images.generated.ts",
  `// Generated by scripts/build-og-images.mjs — do not edit by hand.\n` +
    `// Source photos (public/images/…) that have a 1200×630 JPEG copy in public/og/.\n` +
    `export const OG_IMAGE_DERIVATIVES: ReadonlySet<string> = new Set([\n` +
    built.map((s) => `  "${s}",\n`).join("") +
    `]);\n`,
);
console.log(`Wrote ${built.length} derivatives and lib/og-images.generated.ts`);
